    private void registerBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registerBtnActionPerformed
        // system validation:
        // scenario 1: marking all fields required
        if(nationalIdTxt.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "National ID is Required!", "VALIDATION MESSAGE" , JOptionPane.ERROR_MESSAGE);
        }else if(namesTxt.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Names is Required!", "VALIDATION MESSAGE" , JOptionPane.ERROR_MESSAGE);
        }else if(phoneNumberTxt.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Phone Number is Required!", "VALIDATION MESSAGE" , JOptionPane.ERROR_MESSAGE);
        }else if(emailTxt.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Email is Required!", "VALIDATION MESSAGE" , JOptionPane.ERROR_MESSAGE);
        }else if(ageTxt.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Age is Required!", "VALIDATION MESSAGE" , JOptionPane.ERROR_MESSAGE);
        }else{
            // scenario 2: age should be a number not a character
            // scenario 3: age should be 18 and above
            int age = Integer.parseInt(ageTxt.getText());
            if(age < 18){
                JOptionPane.showMessageDialog(this, "Not allowed age should be equal or above 18!", "VALIDATION MESSAGE" , JOptionPane.ERROR_MESSAGE);
            }else{
                // capture data and send them to model
                
                Client clientObj = new Client();
                clientObj.setAge(age);
                clientObj.setNames(namesTxt.getText());
                clientObj.setEmail(emailTxt.getText());
                clientObj.setNationalId(nationalIdTxt.getText());
                clientObj.setPhoneNumber(phoneNumberTxt.getText());
                
                // sending data to dao
                ClientDao dao = new ClientDao();
                int rowsAffected = dao.registerClient(clientObj);
                if(rowsAffected > 0){
                    JOptionPane.showMessageDialog(this, "Client Added Successful!");
                    addRowsDataToTable();
                }else{
                    JOptionPane.showMessageDialog(this, "Client Failed to be Added!");
                }
                
                
            }            
        }
        
        
    }//GEN-LAST:event_registerBtnActionPerformed

