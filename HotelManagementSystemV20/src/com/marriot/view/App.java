    private void addColumnsHeader(){
        tableModel.addColumn("National ID");
        tableModel.addColumn("Names");
        tableModel.addColumn("Email");
        tableModel.addColumn("Phone Number");
        tableModel.addColumn("Age");
        
        jTable3.setModel(tableModel);
    }
    
    private void addRowsDataToTable(){
        tableModel.setRowCount(0);
        ClientDao dao = new ClientDao();
        List<Client> clients = dao.findAllClients();
        clients.forEach((clientObj) -> {
            tableModel.addRow(new Object[] {
                clientObj.getNationalId(),
                clientObj.getNames(),
                clientObj.getEmail(),
                clientObj.getPhoneNumber(),
                clientObj.getAge()
            });
        });
    }
    

