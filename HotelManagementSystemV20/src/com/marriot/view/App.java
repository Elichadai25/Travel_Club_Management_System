    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        //grap entered values  and we send to model
                                               
                                          
    try {
        Client client = new Client();

        client.setNationalId(NationalIdTxt.getText());
        client.setNames(jTextField2.getText());
        client.setPhoneNumber(jTextField3.getText());
        client.setEmail(emailText.getText());
        client.setAge(Integer.parseInt(jTextField6.getText()));

        ClientDao dao = new ClientDao();
        int result = dao.registerClient(client);

        if(result > 0){
            JOptionPane.showMessageDialog(this, "Saved Successfully!");
        } else {
            JOptionPane.showMessageDialog(this, "Save Failed!");
        }

    } catch(HeadlessException | NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

