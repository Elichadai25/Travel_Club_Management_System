    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        //grap entered values  and we send to model
                                               
                                          
    try {
        Client client = new Client();

        client.setNationalId(nationalIdText.getText());
        client.setNames(namesText.getText());
        client.setPhoneNumber(phoneNumberText.getText());
        client.setEmail(emailText.getText());
        client.setAge(Integer.parseInt(ageText.getText()));

        ClientDao dao = new ClientDao();
        int result = dao.registerClient(client);

        if(result > 0){
            JOptionPane.showMessageDialog(this, "Saved Successfully!");
        } else {
            JOptionPane.showMessageDialog(this, "Save Failed!");
        }

    } catch(Exception e){
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }


    }//GEN-LAST:event_jButton1ActionPerformed

